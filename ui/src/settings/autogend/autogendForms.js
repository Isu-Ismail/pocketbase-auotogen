/**
 * autogendForms.js
 *
 * Form component builders for individual field types in Autogen Data settings:
 *  - System / Pre-configured fields (id, tokenKey, primaryKey)
 *  - Date / Timestamp fields (created, updated, autodate, date fields)
 *    -> Supports "Time of Generation Action" vs "Date / Time Ranges"
 *  - File fields -> Extensions + sample file uploads (Max 5 files <= 500KB)
 *  - Select fields -> Dropdown choices with option deduplication
 *  - Bool fields -> Fixed 2 options (true / false)
 *  - Text fields -> Autogenerate Pattern input
 *  - Number fields -> Min & Max Range inputs + Integer vs Float mode selector
 *  - Email & Password fields
 */

/**
 * Renders a locked, read-only field card for pre-configured autogenerated fields
 */
export function renderSystemFieldCard(field) {
    const patternHint = field.autogeneratePattern
        ? `Pattern: "${field.autogeneratePattern}"`
        : "Autogenerated on record creation";

    return t.div(
        { className: "field-card-spacious disabled-card" },
        t.div(
            { className: "field-card-header" },
            t.div(
                { className: "flex align-center gap-10" },
                t.strong({ className: "txt-lg" }, field.name),
                t.span({ className: "label label-sm secondary" }, field.type),
                t.span({ className: "label label-sm info" }, "Auto Generated"),
            ),
        ),
        t.div(
            { className: "p-10 background-subtle radius txt-hint txt-sm flex align-center justify-between" },
            t.div(
                { className: "flex align-center gap-5" },
                t.i({ className: "ri-lock-line" }),
                t.span({}, `Field "${field.name}" is automatically generated upon record creation.`),
            ),
            t.code({ className: "txt-xs" }, patternHint),
        ),
    );
}

/**
 * Renders Date / Timestamp fields (created, updated, autodate, date)
 */
export function renderDateFieldCard(field, conf, handlers, uniqueId) {
    const isActionTime = conf.dateMode === "action_time" || !conf.dateMode;
    const isSystem = field.system || field.type === "autodate" || field.name === "created" || field.name === "updated";

    return t.div(
        { className: "field-card-spacious" },

        // Header
        t.div(
            { className: "field-card-header" },
            t.div(
                { className: "flex align-center gap-10" },
                t.strong({ className: "txt-lg" }, field.name),
                t.span({ className: "label label-sm secondary" }, field.type),
                isSystem ? t.span({ className: "label label-sm info" }, "System Timestamp") : null,
            ),
        ),

        // Date Generation Mode Switcher
        t.div(
            { className: "flex align-center gap-20 m-b-md" },
            t.span({ className: "txt-hint txt-sm txt-bold" }, "Timestamp Mode:"),
            t.div(
                { className: "field-radio-native" },
                t.input({
                    id: `${uniqueId}_date_act_${field.id}`,
                    type: "radio",
                    name: `date_mode_${field.id}`,
                    checked: () => isActionTime,
                    onchange: () => handlers.toggleDateMode(field.id, "action_time"),
                }),
                t.label({ htmlFor: `${uniqueId}_date_act_${field.id}` }, "Time of Action (Current Execution Time)"),
            ),
            t.div(
                { className: "field-radio-native" },
                t.input({
                    id: `${uniqueId}_date_rng_${field.id}`,
                    type: "radio",
                    name: `date_mode_${field.id}`,
                    checked: () => !isActionTime,
                    onchange: () => handlers.toggleDateMode(field.id, "range"),
                }),
                t.label({ htmlFor: `${uniqueId}_date_rng_${field.id}` }, "Date / Time Ranges (From - To)"),
            ),
        ),

        // MODE 1: Time of Action Banner
        () => {
            if (!isActionTime) return null;

            return t.div(
                { className: "p-12 background-subtle radius txt-hint txt-sm flex align-center gap-10" },
                t.i({ className: "ri-time-line txt-lg" }),
                t.span({}, `Every record created will be timestamped with the exact time of the generation execution.`),
            );
        },

        // MODE 2: Date / Time Ranges controls
        () => {
            if (isActionTime) return null;

            return t.div(
                { className: "date-range-mode-wrapper" },

                // Distribution Mode
                t.div(
                    { className: "flex align-center gap-20 m-b-sm" },
                    t.span({ className: "txt-hint txt-sm txt-bold" }, "Distribution:"),
                    t.div(
                        { className: "field-radio-native" },
                        t.input({
                            id: `${uniqueId}_dist_eq_${field.id}`,
                            type: "radio",
                            name: `dist_${field.id}`,
                            checked: () => conf.distribution === "equal",
                            onchange: () => handlers.toggleDistribution(field.id, "equal"),
                        }),
                        t.label({ htmlFor: `${uniqueId}_dist_eq_${field.id}` }, "Equal Split"),
                    ),
                    t.div(
                        { className: "field-radio-native" },
                        t.input({
                            id: `${uniqueId}_dist_man_${field.id}`,
                            type: "radio",
                            name: `dist_${field.id}`,
                            checked: () => conf.distribution === "manual",
                            onchange: () => handlers.toggleDistribution(field.id, "manual"),
                        }),
                        t.label({ htmlFor: `${uniqueId}_dist_man_${field.id}` }, "Weighted / Manual"),
                    ),
                ),

                // Variations List (From - To Date Pairs)
                t.div(
                    { className: "variations-list-spacious" },
                    () => (conf.dateRanges || []).map((range, idx) => {
                        return t.div(
                            { className: "variation-row-spacious align-center" },
                            t.div(
                                { className: "field m-b-0 flex-1" },
                                t.label({ className: "txt-bold txt-xs m-b-xs" }, "From Date"),
                                t.input({
                                    type: "datetime-local",
                                    className: "input",
                                    value: () => range.from,
                                    onchange: (e) => handlers.updateDateRangePair(field.id, idx, e.target.value, range.to, range.weight),
                                }),
                            ),
                            t.div(
                                { className: "field m-b-0 flex-1" },
                                t.label({ className: "txt-bold txt-xs m-b-xs" }, "To Date"),
                                t.input({
                                    type: "datetime-local",
                                    className: "input",
                                    value: () => range.to,
                                    onchange: (e) => handlers.updateDateRangePair(field.id, idx, range.from, e.target.value, range.weight),
                                }),
                            ),
                            conf.distribution === "manual" ? t.div(
                                { className: "field addon m-b-0" },
                                t.label({ className: "txt-bold txt-xs m-b-xs" }, "Weight"),
                                t.div(
                                    { className: "flex align-center" },
                                    t.input({
                                        type: "number",
                                        className: "input w-90",
                                        min: 0,
                                        max: 100,
                                        value: () => range.weight,
                                        onchange: (e) => handlers.updateDateRangePair(field.id, idx, range.from, range.to, e.target.value),
                                    }),
                                    t.span({ className: "txt-hint txt-xs m-l-5" }, "%"),
                                ),
                            ) : null,
                            t.button(
                                {
                                    type: "button",
                                    className: "btn btn-circle transparent danger m-t-md",
                                    disabled: () => conf.dateRanges.length <= 1,
                                    onclick: () => handlers.removeDateRangePair(field.id, idx),
                                },
                                t.i({ className: "ri-delete-bin-line" }),
                            ),
                        );
                    }),
                ),

                t.button(
                    {
                        type: "button",
                        className: "btn secondary transparent m-t-sm",
                        onclick: () => handlers.addDateRangePair(field.id),
                    },
                    t.i({ className: "ri-add-line" }),
                    t.span({ className: "txt" }, "Add Date Range (From - To)"),
                ),
            );
        },
    );
}

