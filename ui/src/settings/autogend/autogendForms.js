/**
 * Renders File fields with neat styling + Sample File Upload (Max 5 files, <= 500KB each)
 */
export function renderFileFieldCard(field, conf, handlers, uniqueId) {
    const samples = conf.sampleFiles || [];
    const mimeTypes = field.mimeTypes || [];
    const maxSelect = field.maxSelect || 1;

    return t.div(
        { className: "field-card-spacious" },

        // Header
        t.div(
            { className: "field-card-header" },
            t.div(
                { className: "flex align-center gap-10" },
                t.strong({ className: "txt-lg" }, field.name),
                t.span({ className: "label label-sm secondary" }, field.type),
                field.required ? t.span({ className: "label label-sm danger" }, "Required") : null,
                maxSelect > 1 ? t.span({ className: "label label-sm info" }, `Max ${maxSelect} files per record`) : null,
            ),
        ),

        // File Extension / Type Selector
        t.div(
            { className: "field flex-1 m-b-sm" },
            t.label({ className: "txt-bold" }, "Allowed File Type / Extension"),
            t.input({
                type: "text",
                className: "input",
                placeholder: "e.g. png, jpg, webp, pdf",
                value: () => {
                    const val = conf.fileExtension || (mimeTypes.length ? mimeTypes.map((m) => m.split("/")[1] || m).join(", ") : "pdf");
                    return val.replace(/image\//g, "");
                },
                onchange: (e) => handlers.updateFileExtension(field.id, e.target.value),
            }),
            t.div({ className: "field-help" }, "Specify file extensions to generate (e.g. png, jpg, webp, pdf)."),
        ),

        // Sample Files Upload List
        t.div(
            { className: "sample-files-section p-15 radius background-subtle m-t-sm" },
            t.div(
                { className: "flex align-center justify-between m-b-xs" },
                t.label({ className: "txt-bold" }, `Sample Files (${samples.length} / 5 max)`),
                t.span({ className: "txt-hint txt-xs" }, "Max size: 500KB per file"),
            ),

            // Files List
            samples.length ? t.div(
                { className: "variations-list-spacious m-b-sm" },
                () => samples.map((f, idx) => {
                    return t.div(
                        { className: "variation-row-spacious align-center" },
                        t.div(
                            { className: "flex align-center gap-10 flex-1 p-10 background-surface radius border-subtle" },
                            t.i({ className: "ri-file-text-line txt-lg" }),
                            t.div(
                                { className: "flex-1 overflow-hidden" },
                                t.div({ className: "txt-bold txt-ellipsis" }, f.name),
                                t.div({ className: "txt-hint txt-xs" }, `${(f.size / 1024).toFixed(1)} KB`),
                            ),
                        ),
                        t.button(
                            {
                                type: "button",
                                className: "btn btn-circle transparent danger",
                                onclick: () => handlers.removeSampleFile(field.id, idx),
                            },
                            t.i({ className: "ri-delete-bin-line" }),
                        ),
                    );
                }),
            ) : null,

            // Upload Sample File Button
            t.div(
                { className: "upload-file-button-wrapper m-t-xs" },
                t.input({
                    id: `${uniqueId}_file_upload_${field.id}`,
                    type: "file",
                    accept: (() => {
                        const raw = conf.fileExtension || (mimeTypes.length ? mimeTypes.join(",") : "*");
                        if (raw === "*") return "*";
                        return raw
                            .split(",")
                            .map((s) => {
                                const trimmed = s.trim();
                                if (trimmed.includes("/")) {
                                    const parts = trimmed.split("/");
                                    return "." + (parts[1] === "jpeg" ? "jpg" : parts[1]);
                                }
                                return trimmed.startsWith(".") ? trimmed : "." + trimmed;
                            })
                            .join(",");
                    })(),
                    style: "display: none;",
                    onchange: (e) => {
                        const file = e.target.files?.[0];
                        if (!file) return;

                        if (file.size > 500 * 1024) {
                            app.toasts.error(`File "${file.name}" exceeds maximum allowed limit of 500KB!`);
                            e.target.value = "";
                            return;
                        }

                        if (samples.length >= 5) {
                            app.toasts.error("Maximum 5 sample files allowed per field!");
                            e.target.value = "";
                            return;
                        }

                        handlers.addSampleFile(field.id, {
                            name: file.name,
                            size: file.size,
                            type: file.type,
                        });
                        e.target.value = "";
                    },
                }),
                t.button(
                    {
                        type: "button",
                        className: "btn secondary outline sm",
                        disabled: () => samples.length >= 5,
                        onclick: () => {
                            document.getElementById(`${uniqueId}_file_upload_${field.id}`)?.click();
                        },
                    },
                    t.i({ className: "ri-upload-cloud-line" }),
                    t.span(
                        { className: "txt" },
                        samples.length >= 5 ? "Max 5 sample files reached" : "Upload Sample File (Max 500KB)",
                    ),
                ),
            ),
        ),
    );
}

